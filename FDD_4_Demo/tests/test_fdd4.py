"""FDD-4 tests: manifest and preflight validation, output protection, export verification on real
small videos generated by ffmpeg, offline guard, and consistency of the recorded evidence."""
import copy
import json
import shutil
import subprocess
from pathlib import Path

import pytest

from FDD_4_Demo import record_demo as rd

ROOT = Path(__file__).resolve().parents[2]
RAW = json.loads(rd.MANIFEST.read_text(encoding="utf-8"))
HAS_FFMPEG = bool(shutil.which("ffmpeg") and shutil.which("ffprobe"))
needs_ffmpeg = pytest.mark.skipif(not HAS_FFMPEG, reason="ffmpeg/ffprobe not installed")


def write_manifest(tmp_path, mutate):
    data = copy.deepcopy(RAW)
    mutate(data)
    path = tmp_path / "m.json"
    path.write_text(json.dumps(data), encoding="utf-8")
    return path


def test_shipped_manifest_is_valid_and_assets_exist():
    manifest = rd.load_manifest()
    assert manifest["resolution"] == [1920, 1080] and len(manifest["scenes"]) >= 6
    for rel in manifest["assets"].values():
        assert (ROOT / rel).is_file(), rel
    kinds = {s["kind"] for s in manifest["scenes"]}
    assert {"card", "dashboard", "inference", "url", "incidents"} <= kinds
    assert all(s.get("path") != "/docs" for s in manifest["scenes"])  # Swagger UI needs a CDN (not offline)


@pytest.mark.parametrize("mutate,match", [
    (lambda d: d.update(resolution=[1280, 720]), "1920x1080"),
    (lambda d: d.update(fps=5), "fps"),
    (lambda d: d["scenes"].append(copy.deepcopy(d["scenes"][0])), "unique"),
    (lambda d: d["scenes"][4].update(asset="missing_asset"), "unknown asset"),
    (lambda d: d["scenes"][0].update(hold_seconds=0), "hold_seconds"),
    (lambda d: d.pop("scenes"), "missing 'scenes'"),
])
def test_invalid_manifests_rejected(tmp_path, mutate, match):
    with pytest.raises(rd.DemoError, match=match):
        rd.load_manifest(write_manifest(tmp_path, mutate))


def test_missing_and_malformed_manifest(tmp_path):
    with pytest.raises(rd.DemoError, match="not found"):
        rd.load_manifest(tmp_path / "none.json")
    bad = tmp_path / "bad.json"
    bad.write_text("{oops", encoding="utf-8")
    with pytest.raises(rd.DemoError, match="not valid JSON"):
        rd.load_manifest(bad)


def test_preflight_reports_missing_tools_and_assets(tmp_path):
    manifest = rd.load_manifest()
    with pytest.raises(rd.DemoError, match="ffmpeg not found"):
        rd.preflight(manifest, which=lambda name: None)
    broken = copy.deepcopy(manifest)
    broken["assets"]["hazard_sample"] = "tests/assets/does_not_exist.png"
    with pytest.raises(rd.DemoError, match="asset 'hazard_sample' missing"):
        rd.preflight(broken, which=lambda name: f"/usr/bin/{name}")


def test_dry_run_exit_codes(tmp_path, capsys):
    bad = write_manifest(tmp_path, lambda d: d.update(fps=1))
    assert rd.main(["--dry-run", "--manifest", str(bad)]) == 2
    assert "PREFLIGHT FAILED" in capsys.readouterr().out


def test_output_names_are_safe_and_never_overwrite(tmp_path):
    first = rd.safe_output(tmp_path, "demo", "20260101T000000Z")
    first.write_bytes(b"existing take")
    with pytest.raises(rd.DemoError, match="refusing to overwrite"):
        rd.safe_output(tmp_path, "demo", "20260101T000000Z")
    assert first.read_bytes() == b"existing take"
    for bad in ("../escape", "a b", "x;rm"):
        with pytest.raises(rd.DemoError, match="letters, digits"):
            rd.safe_output(tmp_path, bad, "s")


def test_caption_cards_escape_text():
    page = rd.card_html("<script>x</script>", ["a & b"])
    assert "<script>" not in page and "&lt;script&gt;" in page and "a &amp; b" in page


def make_video(path, size="1920x1080", seconds=2):
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
                    f"testsrc=size={size}:rate=30", "-t", str(seconds), "-pix_fmt", "yuv420p", str(path)], check=True)


@needs_ffmpeg
def test_verify_accepts_valid_export_and_rejects_wrong_resolution(tmp_path):
    good = tmp_path / "good.mp4"
    make_video(good)
    checks = rd.verify(good, RAW)
    assert checks["ok"] and checks["width"] == 1920 and checks["height"] == 1080 and checks["audio"] is False
    assert 1.5 < checks["duration_s"] < 2.5 and checks["decodes_cleanly"]
    small = tmp_path / "small.mp4"
    make_video(small, "640x360")
    assert rd.verify(small, RAW)["ok"] is False


@needs_ffmpeg
def test_corrupt_export_raises_clear_error(tmp_path):
    corrupt = tmp_path / "corrupt.mp4"
    corrupt.write_bytes(b"\x00\x00\x00\x18ftypmp42 not really a video")
    with pytest.raises(rd.DemoError, match="ffprobe failed"):
        rd.verify(corrupt, RAW)


def test_recorder_blocks_non_loopback_requests_and_has_no_cloud_clients():
    source = (ROOT / "FDD_4_Demo" / "record_demo.py").read_text(encoding="utf-8")
    assert 'context.route("**/*", guard)' in source and "route.abort()" in source
    assert "host in LOOPBACK" in source
    for banned in ("import requests", "openai", "boto3", "modal"):
        assert banned not in source


def test_scene_kinds_are_all_implemented():
    source = (ROOT / "FDD_4_Demo" / "record_demo.py").read_text(encoding="utf-8")
    for kind in {s["kind"] for s in RAW["scenes"]}:
        assert f'kind == "{kind}"' in source, kind


REPORTS = sorted((ROOT / "reports" / "fdd4" / "demo").glob("recording_*.json"))


@pytest.mark.skipif(not REPORTS, reason="no recording evidence yet")
def test_final_recording_evidence_is_consistent():
    final = json.loads(REPORTS[-1].read_text(encoding="utf-8"))
    checks = final["verification"]
    assert checks["ok"] and checks["width"] == 1920 and checks["height"] == 1080 and checks["decodes_cleanly"]
    assert final["external_requests_blocked"] == []  # fully offline capture
    assert [s["title"] for s in final["scenes"]] == [s["title"] for s in RAW["scenes"]]
    inference = [s for s in final["scenes"] if "click_to_results_s" in s["observed"]]
    assert len(inference) == 2 and all("Defects detected:" in s["observed"]["count_text"] for s in inference)
    video = ROOT / final["video"].replace("\\", "/")
    if video.is_file():
        import hashlib
        assert hashlib.sha256(video.read_bytes()).hexdigest() == final["sha256"]


def test_every_scene_saves_a_live_keyframe_and_startup_is_measured_before_recording():
    source = (ROOT / "FDD_4_Demo" / "record_demo.py").read_text(encoding="utf-8")
